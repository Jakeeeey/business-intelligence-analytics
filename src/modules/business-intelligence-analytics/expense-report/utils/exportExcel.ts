import * as XLSX from "xlsx";
import type { DisbursementRecord, ExpenseFilters } from "../type";

export type ExportExcelOptions = {
  records: DisbursementRecord[];
  filters: ExpenseFilters;
  groupBy?: "coa" | "division";
  userName?: string;
  fileName?: string;
};

const fmtDate = (d?: string) => {
  if (!d) return "";
  try {
    const dt = new Date(d);
    if (Number.isNaN(dt.getTime())) return String(d);
    const yyyy = dt.getFullYear();
    const mm = String(dt.getMonth() + 1).padStart(2, "0");
    const dd = String(dt.getDate()).padStart(2, "0");
    return `${yyyy}-${mm}-${dd}`;
  } catch {
    return String(d);
  }
};

export const getInvoiceNo = (r: DisbursementRecord): string => {
  if (r.invoiceNo && r.invoiceNo.trim()) return r.invoiceNo.trim();
  if (r.referenceNo && r.referenceNo.trim()) return r.referenceNo.trim();
  if (r.docNo && r.docNo.trim()) return r.docNo.trim();
  return "-";
};

export const getInvoiceDate = (r: DisbursementRecord): string => {
  const d = r.invoiceDate || r.lineDate || r.transactionDate;
  return fmtDate(d) || "-";
};

export const getSupplierTin = (r: DisbursementRecord): string => {
  const tin =
    r.supplierTin ||
    r.tin_number ||
    r.tinNumber ||
    r.tin ||
    (r as unknown as Record<string, unknown>).supplierTaxId;
  return tin ? String(tin).trim() : "-";
};

export const getSupplierName = (r: DisbursementRecord): string => {
  const name =
    (r.supplierName && r.supplierName.trim()) ||
    (r.payeeName && r.payeeName.trim());
  return name ? name : "-";
};

export const getVatType = (r: DisbursementRecord): string => {
  if (r.vatType && r.vatType.trim()) {
    const v = r.vatType.trim().toUpperCase();
    if (v.includes("NON")) return "NON-VAT";
    if (v.includes("VAT")) return "VAT";
    return r.vatType.trim();
  }
  if (r.vatNonVat && r.vatNonVat.trim()) return r.vatNonVat.trim();
  if (r.vatStatus && r.vatStatus.trim()) return r.vatStatus.trim();
  if (typeof r.isVat === "boolean") return r.isVat ? "VAT" : "NON-VAT";
  if (typeof r.isVat === "number") return r.isVat === 1 ? "VAT" : "NON-VAT";
  const text = `${r.lineRemarks || ""} ${r.disbursementRemarks || ""} ${r.coaTitle || ""}`.toLowerCase();
  if (text.includes("non-vat") || text.includes("non vat")) return "NON-VAT";
  if (
    text.includes("input vat") ||
    text.includes("input tax") ||
    text.includes("principal net of vat")
  ) {
    return "VAT";
  }
  return "NON-VAT";
};

export const getTypeOfInvoice = (r: DisbursementRecord): string => {
  if (r.typeOfInvoice && r.typeOfInvoice.trim()) return r.typeOfInvoice.trim();
  if (r.invoiceType && r.invoiceType.trim()) return r.invoiceType.trim();
  if (r.supplierType && r.supplierType.trim()) return r.supplierType.trim();
  if (r.transactionTypeName && r.transactionTypeName.trim()) return r.transactionTypeName.trim();
  if (r.lineType && r.lineType.trim()) return r.lineType.trim();
  return "-";
};

export const getAmount = (r: DisbursementRecord): number => {
  return typeof r.lineAmount === "number"
    ? r.lineAmount
    : typeof r.totalAmount === "number"
      ? r.totalAmount
      : 0;
};

export const EXCEL_HEADERS = [
  "Date",
  "Payee",
  "Account",
  "Invoice No.",
  "Invoice Date",
  "Supplier TIN",
  "Supplier Name",
  "VAT/NON-VAT",
  "Type of Invoice",
  "Remarks",
  "Amount (Gross)",
];

export function exportToExcel(options: ExportExcelOptions): void {
  const {
    records = [],
    filters,
    userName = "System",
    fileName,
  } = options;

  // Metadata rows at top
  const dateRangeStr = `${filters?.dateFrom || "-"} to ${filters?.dateTo || "-"}`;
  const metaRows: unknown[][] = [
    ["Disbursement Report"],
    [`Date Range: ${dateRangeStr}`],
    [`Generated By: ${userName}`],
    [`Generated Date: ${new Date().toLocaleString("en-PH")}`],
    [], // blank line before headers
  ];

  // Data rows
  const dataRows: unknown[][] = records.map((r) => [
    fmtDate(r.lineDate || r.transactionDate),
    r.payeeName || "-",
    r.coaTitle || "-",
    getInvoiceNo(r),
    getInvoiceDate(r),
    getSupplierTin(r),
    getSupplierName(r),
    getVatType(r),
    getTypeOfInvoice(r),
    r.lineRemarks || r.disbursementRemarks || "-",
    Number(getAmount(r).toFixed(2)),
  ]);

  // Grand total calculation
  const grandTotal = records.reduce((sum, r) => sum + getAmount(r), 0);
  const totalRow: unknown[] = [
    "GRAND TOTAL",
    "",
    "",
    "",
    "",
    "",
    "",
    "",
    "",
    "",
    Number(grandTotal.toFixed(2)),
  ];

  const fullSheetData: unknown[][] = [
    ...metaRows,
    EXCEL_HEADERS,
    ...dataRows,
    totalRow,
  ];

  const ws = XLSX.utils.aoa_to_sheet(fullSheetData);

  // Column width configuration: ensure adequate, readable widths for all columns
  const minWidths: Record<number, number> = {
    0: 15, // Date
    1: 25, // Payee
    2: 25, // Account
    3: 20, // Invoice No.
    4: 15, // Invoice Date
    5: 20, // Supplier TIN
    6: 30, // Supplier Name
    7: 16, // VAT/NON-VAT
    8: 22, // Type of Invoice
    9: 30, // Remarks
    10: 20, // Amount (Gross)
  };

  const colWidths = EXCEL_HEADERS.map((header, colIndex) => {
    const maxContentLength = Math.max(
      header.length,
      ...dataRows.map((r) => {
        const val = r[colIndex];
        if (val === null || val === undefined) return 0;
        return String(val).length;
      }),
    );
    const minW = minWidths[colIndex] ?? 16;
    return { wch: Math.min(Math.max(maxContentLength + 4, minW), 65) };
  });

  ws["!cols"] = colWidths;

  // Freeze header row so scrolling keeps headers visible
  ws["!freeze"] = { xSplit: 0, ySplit: metaRows.length + 1 };

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, "Disbursement Report");

  const safeDateFrom = filters?.dateFrom || "all";
  const safeDateTo = filters?.dateTo || "all";
  const actualFileName =
    fileName ||
    `Disbursement_Report_${safeDateFrom}_${safeDateTo}_${new Date().toISOString().split("T")[0]}.xlsx`;

  XLSX.writeFile(wb, actualFileName);
}
